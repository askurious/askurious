"""Elementtypen: what every element type can do and what it is for, read from the types themselves (concept
"Elementtypen beschreiben sich selbst", Ralf 2026-10-08, decisions 1 to 5 as recommended).

Every type in the registry (app/items) carries a FactSheet (items.base.FactSheet): what it can do, what it fits and what
not, the study designs it serves and examples we wrote. facts() adds what its class attributes already say
(measurement level, loops, drop-down …), so these cannot go stale. Three readers, one source:

- the page "Elementtypen" (/itemtypes) for signed-in researchers, with how often the type stands in their own
  surveys and those of their groups (never counts from surveys of others: decision 1, first stage);
- AInstein (ainstein_designs.capabilities and details): a short line per type always, the whole fact sheet of the types
  the conversation names (decision 4);
- docs/elementtypen.md, written from here (markdown(); `python tests/items/test_element_types.py --update`, decision 5).

Experimental types appear only for whom they are switched on (app/experimental.py); in the file, all of them.
"""
from flask import Blueprint, render_template, request
from flask_login import current_user

from app import access, experimental, items
from app.ainstein_designs import DESIGN_NAMES
from app.extensions import db
from app.lang import de_en
from app.models import Block, Item

bp = Blueprint("element_types", __name__, url_prefix="/itemtypes")

# the headings of the page and of docs/elementtypen.md, in this order (FactSheet.group)
GROUPS = {
    "classic": ("Klassische Fragen", "Classic questions"),
    "scales": ("Skalen", "Scales"),
    "choice": ("Wahlexperimente", "Choice experiments"),
    "spatial": ("Räumlich und visuell", "Spatial and visual"),
    "tasks": ("Textaufgaben und Reaktionszeit", "Text tasks and reaction time"),
    "feedback": ("Rückmeldung an Teilnehmende", "Feedback to participants"),
    "structure": ("Struktur, Recht und Interview", "Structure, consent and interview"),
}
LEVELS = {"nominal": ("nominal", "nominal"), "ordinal": ("ordinal", "ordinal"), "metric": ("metrisch", "metric")}


def shown(pair):
    """A (German, English) pair in the language of the page."""
    return de_en(pair[0], pair[1])


def pair(kind, name):
    """The (German, English) pair of a Both class attribute of `kind` ("label", "description")."""
    for cls in type(kind).__mro__:
        if name in cls.__dict__:
            value = cls.__dict__[name]
            return (value.de, value.en) if hasattr(value, "de") else (str(value), str(value))
    return ("", "")


def _without_prefix(text):
    return text.removeprefix("Experimentell: ").removeprefix("Experimental: ")


def facts(kind):
    """What the class attributes of `kind` say, as (German, English) pairs, the most telling first."""
    out = []
    if getattr(kind, "interview_only", False):
        out.append(("Nur in Interviewleitfäden", "Interview guides only"))
    if getattr(kind, "experimental", None):
        out.append(("Experimentell: unter „Konto“ einschalten", "Experimental: switch it on under “Account”"))
    requires = getattr(kind, "requires", None)
    if requires and requires in items.REGISTRY:
        de, en = pair(items.REGISTRY[requires], "label")
        out.append((f"Nur in einer Befragung mit {de}", f"Only in a survey with {en}"))
    if kind.computed:
        out.append(("Errechneter Wert statt einer Antwort", "A calculated value, not an answer"))
    elif not kind.collects_answer:
        out.append(("Ohne Antwort", "No answer"))
    if kind.levels:
        de = " oder ".join(LEVELS[v][0] for v in kind.levels)
        en = " or ".join(LEVELS[v][1] for v in kind.levels)
        more = len(kind.levels) > 1
        out.append((f"Messniveau: {de}" + (" (umschaltbar)" if more else ""),
                    f"Measurement level: {en}" + (" (switchable)" if more else "")))
    if kind.result_kind == "scale":
        out.append(("Ergebnisse mit Cronbachs Alpha", "Results with Cronbach’s alpha"))
    if kind.supports_dropdown:
        out.append(("Auch als Dropdown-Liste", "Also as a drop-down list"))
    if kind.supports_map:
        out.append(("Auch als Karte zum Anklicken", "Also as a map to click on"))
    if kind.has_image:
        out.append(("Mit Bildern: hochgeladen oder von der KI", "With images: uploaded or generated by AI"))
    if kind.supports_auto_next:
        out.append(("Kann ohne „Weiter“ von selbst weitergehen", "Can move on without “Next”"))
    if kind.alone_on_page:
        out.append(("Steht allein auf seiner Seite", "Stands alone on its page"))
    if not kind.allowed_in_loop:
        out.append(("Nicht in Schleifen", "Not in loops"))
    if not kind.allowed_in_separated:
        out.append(("Nicht im getrennten Abschnitt", "Not in the separated section"))
    return out


def visible(kind, user=None):
    """Whether `user` (by default the one signed in) is offered `kind`: experimental types only when switched on."""
    feature = getattr(kind, "experimental", None)
    return not feature or experimental.enabled(feature, user)


def grouped(kinds):
    """[(group key, [kinds])] in the order of GROUPS, the kinds in their palette order; empty groups left out."""
    by = {g: [] for g in GROUPS}
    for kind in kinds:
        by[kind.fact_sheet.group].append(kind)
    return [(g, by[g]) for g in GROUPS if by[g]]


def survey_counts(user):
    """{type key: number of surveys it stands in}, over the surveys `user` can open (own ones and those shared with
    their groups, as items.type_counts in the editor's palette). Counts from other surveys never appear (decision 1)."""
    rows = db.session.execute(
        db.select(Item.type, db.func.count(db.distinct(Block.survey_id))).join(Block, Item.block_id == Block.id)
        .filter(Block.survey_id.in_(access.survey_ids(user))).group_by(Item.type))
    return {kind: n for kind, n in rows}


def entry(kind, used=0):
    """One type as the page shows it, in the language of the page."""
    p = kind.fact_sheet
    return {"key": kind.key, "label": kind.label, "description": _without_prefix(kind.description),
            "can": [shown(t) for t in p.can], "good_for": [shown(t) for t in p.good_for],
            "not_for": [shown(t) for t in p.not_for], "examples": [shown(t) for t in p.examples],
            "designs": [(d, shown(DESIGN_NAMES[d])) for d in p.designs], "facts": [shown(f) for f in facts(kind)],
            "keywords": list(p.keywords), "used": used,
            "beta": bool(getattr(kind, "experimental", None))}  # shown as "Closed Beta" (Philipp, 2026-10-10)


def _matches(e, q):
    words = [e["key"], e["label"], e["description"], *e["can"], *e["good_for"], *e["not_for"], *e["examples"],
             *(name for _, name in e["designs"]), *e["facts"], *e["keywords"]]
    hay = " ".join(str(w) for w in words).lower()
    return all(part in hay for part in q.lower().split())


@bp.route("/")
def index():
    """All element types with what each can and is good for. Also without an account (Philipp, 2026-10-09: linked
    from the landing page): then without the counts of one's own surveys and without experimental types."""
    q = (request.args.get("q") or "").strip()[:100]
    design = request.args.get("design") if request.args.get("design") in DESIGN_NAMES else ""
    signed_in = current_user.is_authenticated
    counts = survey_counts(current_user) if signed_in else {}
    kinds = [k for k in items.all_types() if (visible(k) if signed_in else not getattr(k, "experimental", None))]
    groups = []
    for g, members in grouped(kinds):
        shown_entries = [entry(k, counts.get(k.key, 0)) for k in members
                         if (not design or design in k.fact_sheet.designs)]
        if q:
            shown_entries = [e for e in shown_entries if _matches(e, q)]
        if shown_entries:
            groups.append((g, shown(GROUPS[g]), shown_entries))
    return render_template("element_types/index.html", groups=groups, q=q, design=design,
                           designs=[(d, shown(n)) for d, n in DESIGN_NAMES.items()], total=len(kinds),
                           hits=sum(len(e) for _, _, e in groups))


# ---- AInstein (ainstein_designs.capabilities, ainstein._context) ----

def short_line(kind):
    """The line AInstein always gets: name, what it is, the designs it serves, in the language of the page."""
    line = f"- {kind.label}: {_without_prefix(kind.description)}"
    if kind.fact_sheet.designs:
        line += " " + de_en("(passt zu: {d})", "(fits: {d})", d=", ".join(shown(DESIGN_NAMES[d]) for d in kind.fact_sheet.designs))
    return line


def _names(kind):
    """The names under which a conversation may mention `kind`: its label in both languages, and the parts before and
    inside parentheses ("Conjoint (CBC)": "Conjoint", "CBC")."""
    names = set()
    for label in pair(kind, "label"):
        names.add(label)
        if "(" in label:
            head, _, inner = label.partition("(")
            names.update({head.strip(), inner.rstrip(")").strip()})
        names.update(part.strip() for part in label.split("/") if "/" in label)
    return {n for n in names if len(n) >= 3}


MAX_DETAILS = 8


def named_in(text, user=None):
    """The types (visible to `user`) that `text` mentions by name, in palette order, at most MAX_DETAILS."""
    import re

    found = []
    for kind in items.all_types():
        if not visible(kind, user) or getattr(kind, "interview_only", False):
            continue
        if any(re.search(r"(?<!\w)" + re.escape(n) + r"(?!\w)", text) for n in _names(kind)):
            found.append(kind)
    return found[:MAX_DETAILS]


def details(kind):
    """The whole fact sheet of `kind` for AInstein, in the language of the page."""
    p = kind.fact_sheet
    lines = [f"{kind.label}:"]
    for title, texts in ((("kann", "can do"), p.can), (("passt für", "fits"), p.good_for),
                         (("passt nicht für", "does not fit"), p.not_for), (("Beispiele", "examples"), p.examples),
                         (("Eigenschaften", "properties"), facts(kind))):
        if texts:
            lines.append(f"  {shown(title)}: " + "; ".join(shown(t) for t in texts))
    return "\n".join(lines)



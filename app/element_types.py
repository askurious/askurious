DOC_HEAD = """# Elementtypen von Askurious

Alle Elementtypen des Fragebogens: was sie können, wofür sie passen und wofür nicht.
Jeder Typ steht mit seinem Schlüssel im Code (`app/items/<schlüssel>.py`) in Klammern.
Experimentelle Typen erscheinen nur, wenn man sie unter „Konto“ einschaltet (`app/experimental.py`).

Diese Datei wird erzeugt, aus dem Steckbrief jedes Typs (`fact_sheet` in `app/items/`, gelesen von `app/element_types.py`).
Nicht von Hand ändern: den Steckbrief ändern und dann `python tests/items/test_element_types.py --update`.
Dieselben Texte zeigt die Seite „Elementtypen“ (`/itemtypes`), auf Deutsch und Englisch, und AInstein liest sie.
"""


def _line(title, texts, sep="; "):
    text = sep.join(t[0] for t in texts)
    return f"  - {title}: {text}" + ("" if text.endswith((".", "?", "!")) else ".")


def markdown():
    """docs/elementtypen.md, in German, every registered type (experimental ones too)."""
    out = [DOC_HEAD]
    for g, members in grouped(items.all_types()):
        out.append(f"## {GROUPS[g][0]}\n")
        for kind in members:
            mark = ", experimentell" if getattr(kind, "experimental", None) else (
                ", nur in Interviewleitfäden" if getattr(kind, "interview_only", False) else "")
            out.append(f"- **{pair(kind, 'label')[0]}** (`{kind.key}`{mark})")
            p = kind.fact_sheet
            out += [f"  - {t[0]}" for t in p.can]
            out.append(_line("Passt für", p.good_for))
            if p.not_for:
                out.append(_line("Passt nicht für", p.not_for))
            if p.designs:
                out.append(_line("Designs", [DESIGN_NAMES[d] for d in p.designs], ", "))
            if p.examples:
                out.append(_line("Beispiele", p.examples))
        out.append("")
    return "\n".join(out).rstrip() + "\n"

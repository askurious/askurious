"""Write requirements.lock: every package the server needs, also the indirect ones (Werkzeug, Jinja2, urllib3, ...),
with its exact version and the SHA-256 of its wheels (security audit 2026-10-04, H4).

requirements.txt pins only the packages the app imports itself; what they pull in came in whatever version was
current when vendor.zip was built. The lock fixes all of them, and `pip install --require-hashes` refuses a file
whose content differs from the one locked here.

The servers are Linux (manylinux, x86_64) with CPython 3.11 (Plesk hosting) and 3.12 (another Plesk server), so the
lock holds the wheels for both. requirements-postgres.txt (psycopg) is part of it: on a server with SQLite it is
installed and never imported.

    python tools/lock_requirements.py            # writes requirements.lock next to requirements.txt (and the next)
    python tools/lock_requirements.py docker     # only deploy/docker/requirements-docker.lock

The Docker image (deploy/docker/Dockerfile, CPython 3.12) also installs gunicorn and its packaging; they are locked
the same way in deploy/docker/requirements-docker.lock from requirements-docker.txt (code audit 2026-10-08, B11).
    python tools/check_vulnerabilities.py        # asks OSV about every locked version (also done by deploy/docker/deploy-docker.sh)

Needs pip and access to PyPI; nothing is installed (pip install --dry-run --report).
"""
import json
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PYTHONS = ("3.11", "3.12")
PLATFORMS = ("manylinux2014_x86_64", "manylinux_2_17_x86_64", "manylinux_2_28_x86_64")
SOURCES = ("requirements.txt", "requirements-postgres.txt")
DOCKER = ("deploy/docker/requirements-docker.txt",)
DOCKER_PYTHONS = ("3.12",)


def resolve(python, sources=SOURCES):
    """{name: (version, {sha256, ...})} as pip would install it for this Python on the servers."""
    with tempfile.TemporaryDirectory() as tmp:
        report = os.path.join(tmp, "report.json")
        cmd = [sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet", "--report", report,
               "--target", os.path.join(tmp, "t"), "--python-version", python, "--implementation", "cp",
               "--only-binary=:all:", *[a for p in PLATFORMS for a in ("--platform", p)],
               *[a for s in sources for a in ("-r", os.path.join(HERE, s))]]
        subprocess.run(cmd, check=True)
        with open(report, encoding="utf-8") as f:
            data = json.load(f)
    out = {}
    for entry in data["install"]:
        name = entry["metadata"]["name"].lower().replace("_", "-")
        digest = entry["download_info"].get("archive_info", {}).get("hashes", {}).get("sha256")
        if not digest:
            raise SystemExit(f"{name}: pip reported no SHA-256")
        out[name] = (entry["metadata"]["version"], {digest})
    return out


def write(target, sources, pythons, usage):
    merged = {}
    for python in pythons:
        for name, (version, hashes) in resolve(python, sources).items():
            if name in merged and merged[name][0] != version:
                raise SystemExit(f"{name}: {merged[name][0]} for one Python, {version} for another; pin it in {sources[0]}")
            merged.setdefault(name, (version, set()))[1].update(hashes)
    lines = ["# Generated by tools/lock_requirements.py from " + " and ".join(sources) + " for CPython "
             + " and ".join(pythons) + " on Linux x86_64. Do not edit; run the tool again after changing them.",
             usage, ""]
    for name in sorted(merged):
        version, hashes = merged[name]
        lines.append(f"{name}=={version} \\")
        lines += [f"    --hash=sha256:{h} \\" for h in sorted(hashes)]
        lines[-1] = lines[-1][:-2]
    with open(os.path.join(HERE, target), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{target}: {len(merged)} packages")


def main():
    if sys.argv[1:] != ["docker"]:
        write("requirements.lock", SOURCES, PYTHONS,
              "# pip install --require-hashes --only-binary=:all: ... -r requirements.lock")
    write("deploy/docker/requirements-docker.lock", DOCKER, DOCKER_PYTHONS,
          "# pip install --require-hashes --no-deps -r requirements-docker.lock (see deploy/docker/Dockerfile)")


if __name__ == "__main__":
    main()
